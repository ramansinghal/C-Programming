//print numbers from 0-10
#include<stdio.h>
int main() {
    for(int i=0 ; i<=10 ; i++) {
        printf("%d\n",i);
    }
    return 0;
}


//print numbers from 10-0
#include<stdio.h>
int main() {
    for(int i=10 ; i>=0 ; i--) {
        printf("%d\n",i);
    }
    return 0;
}