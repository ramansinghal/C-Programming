//print helloworld 5 times
#include<stdio.h>
int main() {
    int i=0;
    while(i<5){
        printf("helloworld\n");
        i++;
    }
    return 0;
}


//print number from 1-5
#include<stdio.h>
int main() {
    int i = 1;
    while(i <= 5){
        printf("%d\n",i);
        i++;
    }
    return 0;
}


//print numbers from 5-1
#include<stdio.h>
int main() {
    int i=5;
    while(i>=1){
        printf("%d\n",i);
        i--;
    }
    return 0;
}